def main():
    script_dir = Path(__file__).resolve().parent
    platform_dir = script_dir.parents[1]

    print("Executing GradMent Database Schema Inventory Discovery (Live MySQL)...")
    tables = query_live_mysql()

    output_dir = platform_dir / "docs"
    output_dir.mkdir(parents=True, exist_ok=True)

    report_path = output_dir / "schema_inventory.md"
    report_content = generate_markdown_report(tables)
    report_path.write_text(report_content, encoding="utf-8")

    json_path = output_dir / "schema_inventory.json"
    json_path.write_text(json.dumps(tables, indent=2), encoding="utf-8")

    print(f"Successfully generated inventory report: {report_path}")
    print(f"Successfully generated JSON schema dump: {json_path}")

if __name__ == "__main__":
    main()
