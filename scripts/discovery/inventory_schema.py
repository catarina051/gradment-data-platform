#!/usr/bin/env python3
"""
GradMent Data Platform — Schema Inventory Discovery Script
Discovers and inventories operational database tables, columns, data types, nullability,
and foreign key relationships from live MySQL or PHP migration files.
"""

import os
import re
import sys
import json
import subprocess
from pathlib import Path

def query_live_mysql() -> dict:
    """Queries live MySQL database via PHP PDO helper to extract exact physical schema."""
    script_path = Path(__file__).resolve().parent / "query_local_db.php"
    if not script_path.exists():
        return {}
    
    try:
        proc = subprocess.run(["php", str(script_path)], capture_output=True, text=True, check=True)
        data = json.loads(proc.stdout)
        if isinstance(data, dict) and "error" not in data:
            return data
        return {}
    except Exception as e:
        print(f"Notice: Live MySQL query warning: {e}", file=sys.stderr)
        return {}

